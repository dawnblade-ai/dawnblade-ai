const G: any = globalThis;
const ORIGINS = ["https://dawnblade-ai.github.io", "null", ...(Deno.env.get("TABLE_ORIGINS") || "").split(",").map((s: string) => s.trim()).filter(Boolean)];
/* TEST HOOK, leave unset: the first uid a deal hands out. 0 is the page's own (the catalog hash covers card uids, so a
   deployed function MUST deal from 0). tools/supabase-rehearse.js sets 100000 so its blindness scan can tell a hidden
   uid from any other number, as the drills do. */
const UID0 = Number(Deno.env.get("TABLE_UID0") || 0) || 0;
const MAX_BODY = 256 * 1024;                 // a request is one frame; the largest is a few KB
const MAX_BROADCAST = 240_000;               // Realtime's HTTP endpoint refuses ~250 KB payloads (measured 2026-11-13: 250,000 ok, 260,000 422)

/* ---- the card database and the deal, built once per instance, on the first request ---------------------- */
let READY: any = null;
function ready(){
  if(READY) return READY;
  const win: any = {};
  runData(win);                              // window.CDN, APP_VER, DATA_VER, HEROES, DECKS (index.html's data script, verbatim)
  runPool.call(G, win);                      // window.DAWN_POOL (data/pool.js, verbatim)
  G.DawnCards.setCDN(win.CDN);
  const db = G.DawnCards.buildMaps(win.DAWN_POOL.filter((c: any) => c && c.name).map(G.DawnCards.mapDbCard));
  G.DawnJudge.setDb(db);
  const heroes = Object.fromEntries(win.HEROES.map((h: any) => [h.k, h]));
  const decks = Object.fromEntries(win.HEROES.map((h: any) => [h.k, G.DawnGame.parseDeck(win.DECKS[h.k])]));
  const deal = (spec: any) => {
    const m = G.DawnBuild.buildMatch(spec, {db, heroes, decks, ctr0: UID0});
    const state = G.DawnJudge.newMatch({builds: m.builds, names: m.names, heroKeys: m.heroKeys, first: m.first, seed: m.seed});
    const catalog = G.DawnWire.makeCatalog(m.builds.flatMap((b: any) => [...(b.deck || []), ...(b.gear || []), ...(b.startItem ? [b.startItem.card] : [])]));
    return {state, catalog};
  };
  READY = {deal, build: G.DawnLobby.buildId(win.APP_VER, win.DATA_VER), appVer: win.APP_VER, dataVer: win.DATA_VER};
  return READY;
}

/* ---- the two providers ----------------------------------------------------------------------------------- */
function conf(){
  const url = (Deno.env.get("SUPABASE_URL") || "").replace(/\/+$/, "");
  const key = Deno.env.get("TABLE_SERVICE_KEY") || Deno.env.get("SUPABASE_SERVICE_ROLE_KEY") || "";
  if(!url || !key) throw new Error("the function has no SUPABASE_URL / service key in its environment");
  /* a legacy key is a JWT (sent as apikey AND bearer); a new secret key ("sb_secret_…") goes in `apikey` alone. UNVERIFIED for the latter. */
  const headers: any = {apikey: key, "content-type": "application/json"};
  if(!key.startsWith("sb_")) headers.authorization = "Bearer " + key;
  return {url, headers};
}
/* ---- timing (PERF, 2026-11-14): every response carries `Server-Timing` and `x-table-meta` headers (never the body, so no page
   or drill can depend on them): where this request's milliseconds went inside the function. `ready` = building the card database
   and deal (cold instance only), `get` = the row SELECT, `put` = table_put, `bc` = the Realtime broadcast call(s), `app` =
   everything else (parse, rehydrate the hub, apply the frame, serialise); `inst` names the instance, `seq` counts its requests,
   `cold` is 1 on its first, `up` is ms since the isolate started, `rowb` is the stored row's size in bytes as read. One ctx per request: instances serve requests
   concurrently. */
const INST = Math.random().toString(36).slice(2, 8);
let SEQ = 0;
const nowMs = () => performance.now();
function mkCtx(){ return {t0: nowMs(), ready: 0, get: 0, put: 0, bc: 0, nbc: 0, rowb: 0, seq: ++SEQ}; }
function timingHeaders(c: any, cold: boolean){
  const total = nowMs() - c.t0, app = Math.max(0, total - c.ready - c.get - c.put - c.bc), f = (x: number) => x.toFixed(1);
  return {"server-timing": "ready;dur=" + f(c.ready) + ", get;dur=" + f(c.get) + ", put;dur=" + f(c.put) + ", bc;dur=" + f(c.bc) + ", app;dur=" + f(app) + ", total;dur=" + f(total),
          "x-table-meta": "inst=" + INST + ";seq=" + c.seq + ";cold=" + (cold ? 1 : 0) + ";rowb=" + c.rowb + ";nbc=" + c.nbc + ";up=" + Math.round(nowMs()),
          "access-control-expose-headers": "server-timing, x-table-meta"};
}
const mkStore = (c: any) => ({
  async get(id: string){
    const t = nowMs();
    try {
      const k = conf();
      const r = await fetch(k.url + "/rest/v1/tables?id=eq." + encodeURIComponent(id) + "&select=version,row", {headers: k.headers});
      if(!r.ok) throw new Error("store.get " + r.status);
      const text = await r.text(); c.rowb = text.length;
      const rows = JSON.parse(text);
      return rows.length ? {version: rows[0].version, row: rows[0].row} : null;
    } finally { c.get += nowMs() - t; }
  },
  async put(id: string, row: any, expected: number){
    const t = nowMs();
    try {
      const k = conf();
      const r = await fetch(k.url + "/rest/v1/rpc/table_put", {method: "POST", headers: k.headers, body: JSON.stringify({p_id: id, p_row: row, p_expected: expected})});
      if(!r.ok) throw new Error("store.put " + r.status);
      const v = await r.json();                 // table_put returns the new version, or 0 for "someone wrote first"
      return v > 0 ? {ok: true, version: v} : {ok: false, version: expected};
    } finally { c.put += nowMs() - t; }
  }
});
const mkBroadcast = (c: any) => async (topic: string, payload: any) => {
  const body = JSON.stringify({messages: [{topic, event: "frame", payload, private: false}]});
  if(body.length > MAX_BROADCAST) throw new Error("broadcast too large: " + body.length);
  const t = nowMs();
  try {
    const k = conf();
    const r = await fetch(k.url + "/realtime/v1/api/broadcast", {method: "POST", headers: k.headers, body});
    if(!r.ok) throw new Error("broadcast " + r.status);          // 202 is success (measured)
  } finally { c.bc += nowMs() - t; c.nbc++; }
};

/* ---- identity (S4.1) — UNVERIFIED, NOT DEPLOYED, INERT UNLESS A JOIN PRESENTS A TOKEN -------------------------------------
   referee.js asks `deps.identify(token) -> {player, name?} | null` and nothing else; this is the Supabase end of that seam.
     1. VERIFY the token with the provider: GET <project>/auth/v1/user with `apikey` (the project's key) and `Authorization: Bearer
        <the player's token>`. GoTrue checks signature, expiry and session; a 401/403 is "forged or expired" -> null (the referee
        answers "identity" and changes nothing). Any other failure (network, 5xx) THROWS: the referee answers "internal" — a provider
        outage is not a verdict on the token. We never decode the JWT ourselves.
     2. MAP it onto OUR player: POST /rest/v1/rpc/identity_resolve (002_players.sql) with (provider, the user's id): the same
        sign-in is always the same player; first sight creates one. provider = "supabase-anon" for an anonymous user (planned first
        provider, NOT enabled on the project yet, pending the user's permission), "supabase" otherwise.
   The token, the provider's user id and OUR player id never reach a log line, a response or a broadcast (referee.js keeps them in
   the row's `owners` only). UNVERIFIED against the real services: the exact /auth/v1/user headers (publishable vs service key as
   `apikey`) and identity_resolve's table-return shape over PostgREST — both are what tools/supabase-stub.js stands in for. */
const mkIdentify = (c: any) => async (token: string) => {
  const t = nowMs();
  try {
    const k = conf();
    const who = await fetch(k.url + "/auth/v1/user", {headers: {apikey: k.headers.apikey, authorization: "Bearer " + token}});
    if(who.status === 401 || who.status === 403) return null;
    if(!who.ok) throw new Error("identify.verify " + who.status);
    const u: any = await who.json();
    if(!u || typeof u.id !== "string" || !u.id || u.id.length > 256) return null;
    const r = await fetch(k.url + "/rest/v1/rpc/identity_resolve", {method: "POST", headers: k.headers,
      body: JSON.stringify({p_provider: u.is_anonymous ? "supabase-anon" : "supabase", p_subject: u.id, p_name: null})});
    if(!r.ok) throw new Error("identify.resolve " + r.status);
    const rows: any = await r.json();
    const row = Array.isArray(rows) ? rows[0] : rows;
    if(!row || typeof row.player_id !== "string") throw new Error("identify.resolve answered no player");
    return {player: row.player_id, ...(row.display_name ? {name: row.display_name} : {})};
  } finally { c.get += nowMs() - t; }
};

/* ---- HTTP ----------------------------------------------------------------------------------------------- */
function cors(req: Request){
  const origin = req.headers.get("origin");
  const h: any = {"access-control-allow-methods": "POST, GET, OPTIONS", "access-control-allow-headers": "authorization, x-client-info, apikey, content-type",
                  "access-control-max-age": "86400", vary: "Origin"};
  if(origin && ORIGINS.includes(origin)) h["access-control-allow-origin"] = origin;
  return h;
}
const send = (req: Request, body: any, status = 200, extra: any = {}) => new Response(JSON.stringify(body), {status, headers: {...cors(req), "content-type": "application/json", ...extra}});

Deno.serve(async (req: Request) => {
  if(req.method === "OPTIONS") return new Response(null, {status: 204, headers: cors(req)});
  if(req.method === "GET"){
    /* a health line you can open in a browser: the build this function plays (not a secret) */
    try { const r = ready(); return send(req, {service: "dawnblade-table", build: r.build}); } catch(e){ console.error(e); return send(req, {service: "dawnblade-table", error: "not ready"}, 500); }
  }
  if(req.method !== "POST") return send(req, {ok: false, refused: "bad-request"}, 405);
  let request: any;
  try {
    const text = await req.text();
    if(text.length > MAX_BODY) return send(req, {ok: false, refused: "bad-request"});
    request = JSON.parse(text);
  } catch(_){ return send(req, {ok: false, refused: "bad-request"}); }
  const c = mkCtx(), cold = !READY;
  let r: any;
  const tr = nowMs();
  try { r = ready(); } catch(e){ console.error(e); return send(req, {ok: false, refused: "internal"}); }
  c.ready = nowMs() - tr;
  const answer = await G.DawnServer.handle(request, {store: mkStore(c), broadcast: mkBroadcast(c), deal: r.deal, build: r.build, now: () => Date.now(),
    ...(Deno.env.get("TABLE_IDENTITY") === "off" ? {} : {identify: mkIdentify(c)}),
    log: (e: any) => console.error(String(e && e.stack || e))});          // operator logs only; an error never rides a response
  return send(req, answer, 200, timingHeaders(c, cold));
});
