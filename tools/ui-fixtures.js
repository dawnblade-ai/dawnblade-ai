#!/usr/bin/env node
/* tools/ui-fixtures.js — CRESCENDO's lab fixtures, from REAL games (never hand-authored).
     docs/crescendo/mockups/prompts-fixture.js   window.PROMPT_FIXTURES: real built prompts (one per tag+title, a few each) and
                                                 the shapes real games did not raise, built by `buildPrompt` over real cards
     docs/crescendo/mockups/announce-tape.js     window.ANNOUNCE_TAPE: a recorded self-played game as `beatsFor` descriptors
                                                 (seat 0's viewpoint), plus the steps around its KO
   Deterministic (fixed seeds). Rerun after any change to engine/announce.js, prompts.js or ui/announce-view.js's descriptors:
     node tools/ui-fixtures.js */
const fs = require("fs");
const path = require("path");
const PM = require("../engine/prompts.js");
const built = [], realBuild = PM.buildPrompt;
PM.buildPrompt = function(game, spec){ const r = realBuild.apply(this, arguments); if(r) built.push(r); return r; };
const T = require("../tools/tournament.js");
const AV = require("../ui/announce-view.js");
const J = require("../engine/judge.js"), L = require("../engine/local.js"), SP = require("../engine/sparring.js");
const B = require("../engine/build.js"), C = require("../engine/cards.js"), G = require("../engine/game.js"), RNG = require("../engine/rng.js");
const X = require("../test/helpers/extract.js");

const OUT = path.join(__dirname, "..", "docs", "crescendo", "mockups");
const KEEP = ["name", "uid", "pitch", "cost", "power", "def", "life", "tt", "tx", "img", "dbImg", "hidden", "kind"];
const slim = c => { if(!c) return c; const o = {}; for(const k of KEEP) if(c[k] !== undefined) o[k] = c[k]; return o; };
const slimPrompt = p => {
  const o = {tag: p.tag, side: p.side, src: p.src, title: p.title, hint: p.hint, sel: [], down: [], cards: (p.cards || []).map(slim)};
  for(const k of ["n", "keepTop", "order", "min", "max", "optional", "filters", "cost", "avail", "exactPitch", "amount", "choice", "options"])
    if(p[k] !== undefined) o[k] = p[k] && p[k].map ? p[k].map(x => x && typeof x === "object" ? JSON.parse(JSON.stringify(x, (k2, v) => k2 === "ops" ? [] : v)) : x) : p[k];
  return o;
};

/* ---- prompts ---- */
const E = T.ENTRANTS;
for(let i = 0; i < E.length; i += 3) T.leg(E[i], E[(i + 1) % E.length], "ui-" + i, 0);
const picked = [], seen = {};
for(const p of built){
  const k = p.tag + "|" + p.title;
  if(seen[k] || (picked.filter(x => x.tag === p.tag).length >= 3)) continue;
  seen[k] = 1; picked.push(p);
}
const pool = built.filter(p => p.cards && p.cards.length >= 3)[0].cards;
const real = pool.slice(0, 3);
const g0 = {sides: [{hand: real.slice(), deck: real.slice(), grave: [], board: [], gear: [], res: 2}, {}], turn: 1};
const syn = (spec) => PM.buildPrompt(g0, Object.assign({side: 0, src: real[0].name}, spec));
const extra = [
  syn({tag: "modal", optional: true, options: [{label: "Discard a card", ops: []}, {label: "Destroy the top card of your deck", ops: []}], title: real[0].name + " — pay to power it?"}),
  syn({tag: "modal", options: [{label: "On top of your deck", ops: []}, {label: "On the bottom", ops: []}], title: "Choose where it goes"}),
  syn({tag: "target", cards: [Object.assign({}, real[0], {name: "Your hero", life: 24}), Object.assign({}, real[1], {name: "Their ally", kind: "ally"})]}),
  syn({tag: "reveal", cards: real, title: "Their hand", hint: "Both players see this."}),
  syn({tag: "alloc", cards: real, n: 3}),
  syn({tag: "pick", cards: real, min: 0, max: 2, title: "Choose up to 2"}),
  syn({tag: "opt", cards: real, n: 3, keepTop: true, title: "Reorder the top 3"})
].filter(Boolean);
const prompts = [...picked, ...extra].map(slimPrompt);
fs.writeFileSync(path.join(OUT, "prompts-fixture.js"), "/* generated by tools/ui-fixtures.js from real games — never edit */\nwindow.PROMPT_FIXTURES = " + JSON.stringify(prompts) + ";\n");

/* ---- the tape ---- */
const DATA = X.loadData(), db = C.buildMaps(X.readCards(X.cardDbPath()).filter(c => c && c.name).map(C.mapDbCard));
const [k0, k1, seed, first] = ["kayo", "dorinthea", "ann1", 0];
const h0 = DATA.HEROES.find(h => h.k === k0), h1 = DATA.HEROES.find(h => h.k === k1), ctr = {n: 0};
let rng = RNG.make(seed);
const b0 = B.buildSideDefault(h0, G.parseDeck(DATA.DECKS[h0.k]), db, rng, ctr); rng = b0.rng;
const b1 = B.buildSideDefault(h1, G.parseDeck(DATA.DECKS[h1.k]), db, rng, ctr); rng = b1.rng;
const g = J.newMatch({builds: [b0.b, b1.b], names: [h0.n, h1.n], heroKeys: [h0.k, h1.k], rng, first, tokSeq: ctr.n});
const steps = [];
const s = L.createLocal({seat: 0, state: g, reduce: J.reduce, legal: J.legal, policy: (st, i) => SP.act(st, i), onStep: e => steps.push(e)});
s.start();
for(let i = 0; i < 4000 && !s.state().over; i++){ const a = SP.act(s.state(), 0); if(!a) break; if(s.submit(a)) break; }
const names = [g.sides[0].name, g.sides[1].name];
const told = steps.map(st => AV.beatsFor(st, 0, {names})).map(ds => ds.map(d => JSON.parse(JSON.stringify(d, (k, v) => k === "line" && v && typeof v === "object" ? undefined : (v && v.tt !== undefined && v.name !== undefined ? slim(v) : v)))));
const idx = told.map((d, i) => d.length ? i : -1).filter(i => i >= 0);
const take = new Set([...idx.slice(0, 70), ...idx.slice(-8)]);
const tape = {names, maxLife: [g.sides[0].maxHp, g.sides[1].maxHp], game: k0 + " vs " + k1, steps: [...take].sort((a, b) => a - b).map(i => told[i])};
fs.writeFileSync(path.join(OUT, "announce-tape.js"), "/* generated by tools/ui-fixtures.js from a real self-played game — never edit */\nwindow.ANNOUNCE_TAPE = " + JSON.stringify(tape) + ";\n");
console.log("prompts", prompts.length, prompts.map(p => p.tag).join(","), "| tape steps", tape.steps.length, "descriptors", tape.steps.reduce((n, d) => n + d.length, 0));
