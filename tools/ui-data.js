#!/usr/bin/env node
/* ============================================================
   ui/data.js — GENERATED from index.html's plain data <script>, never hand-edited.

   play.html (the CRESCENDO shell) needs window.CDN / SERVER_TABLE / APP_VER / DATA_VER / HEROES / DECKS / ...
   exactly as index.html declares them. There is ONE hand-kept copy (index.html's data script); this writes
   the second one byte for byte, so the two pages cannot disagree about a deck list or a version.

   The slice is test/helpers/extract.js `loadData`'s: from the first `window.CDN` to that script's `</script>`.

     node tools/ui-data.js           write ui/data.js
     node tools/ui-data.js --check   exit 1 if ui/data.js is stale (test/ui-sync.test.js runs this)
   ============================================================ */
"use strict";
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const OUT = path.join(ROOT, "ui", "data.js");

const HEADER =
`/* GENERATED by tools/ui-data.js from index.html's data <script> (from window.CDN to its closing tag).
   DO NOT EDIT BY HAND: change index.html, then run \`node tools/ui-data.js\`. test/ui-sync.test.js fails a stale copy. */
`;

function build(){
  const src = fs.readFileSync(path.join(ROOT, "index.html"), "utf8");
  const start = src.indexOf("window.CDN");
  if(start < 0) throw new Error("ui-data: index.html's data script (window.CDN) was not found");
  const end = src.indexOf("</script>", start);
  if(end < 0) throw new Error("ui-data: the data script has no closing tag");
  return HEADER + src.slice(start, end).replace(/\s+$/, "") + "\n";
}

module.exports = { build, OUT };

if(require.main === module){
  const want = build();
  if(process.argv.includes("--check")){
    const have = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : null;
    if(have !== want){ console.error("ui/data.js is " + (have == null ? "missing" : "stale") + " — run: node tools/ui-data.js"); process.exit(1); }
    console.log("ui/data.js is current (" + want.length + " bytes)");
  } else {
    fs.writeFileSync(OUT, want);
    console.log("wrote ui/data.js (" + want.length + " bytes)");
  }
}
