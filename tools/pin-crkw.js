#!/usr/bin/env node
/* ============================================================
   PIN THE KEYWORDS — what each keyword MEANS, from the Comprehensive Rules.

   The hero sheet shows the keywords a deck uses (`cards.deckKeywords`,
   v6.60). A newcomer who taps "Boost" or "Phantasm" should read what it
   means, and the only honest source is the Comprehensive Rules' own
   chapter 8: each ability, label and effect keyword opens with one
   sentence that defines it ("Go again is a special resolution ability that
   means "Gain 1 action point.""). This tool fetches that chapter and keeps
   each keyword's NUMBER, NAME and that FIRST PARAGRAPH, verbatim. Nothing
   is paraphrased; an icon (an <img> with alt "{p}") is kept as its token,
   the way card text keeps it, and the page tints it (`pipParts`).

   IT IS FETCHED DATA, NEVER AUTHORED, like data/pool.js: a `<script src>`
   (file:// refuses fetch) that assigns `window.DAWN_CRKW`, and
   `module.exports` under Node. The page never fetches the rules site.

   WHICH SECTIONS: 8.3 (ability keywords), 8.4 (label keywords) and 8.5
   (effect keywords) — the three a card's keyword index names. 8.1 / 8.2
   (types and subtypes) and 8.6 (tokens) are not keywords a deck "uses".

     node tools/pin-crkw.js            # rewrite data/crkw.js
     node tools/pin-crkw.js --check    # fetch and diff, write nothing (exit 1 on a difference)

   Rerun it each release cycle beside the pool's re-pin; test/crkw.test.js
   holds the pinned file's shape and that every keyword a deck uses has a row.
   ============================================================ */
"use strict";
const fs = require("fs");
const path = require("path");

const SRC = "https://rules.fabtcg.com/en/cr/08-keywords/";
const OUT = path.join(__dirname, "..", "data", "crkw.js");

const decode = s => s.replace(/&nbsp;/g, " ").replace(/&amp;/g, "&").replace(/&lt;/g, "<").replace(/&gt;/g, ">")
  .replace(/&quot;/g, "\"").replace(/&#39;|&#x27;|&rsquo;/g, "'").replace(/&ldquo;|&rdquo;/g, "\"")
  .replace(/&#(\d+);/g, (_, n) => String.fromCharCode(+n));
/* one HTML fragment as plain text: an icon becomes its alt token, tags go, space collapses */
const text = h => decode(h.replace(/<img[^>]*\balt="([^"]*)"[^>]*>/g, "$1").replace(/<[^>]+>/g, ""))
  .replace(/\s+/g, " ").trim();

/* The chapter's markup, read the way the site writes it (2026-11-22):
     <div class="rule" id="cr8.3.5"><p><span class="rule-number">8.3.5</span>
       <strong>Go again</strong><br />Go again is a special resolution …</p></div>
   then `subrule` divs for 8.3.5a …. The name is the <strong>; the definition is
   what follows the line break (or the next paragraph). A cross-reference
   (<sup><a>[5.3.5]</a></sup>) is a link to another rule, not wording, and is
   dropped. */
function parse(html){
  const rows = {};
  const re = /<div class="rule" id="cr(8\.[345]\.\d+)">([\s\S]*?)<\/div>/g;
  let m;
  while((m = re.exec(html))){
    const inner = m[2].replace(/<sup>[\s\S]*?<\/sup>/g, "");
    const nm = inner.match(/<strong>([\s\S]*?)<\/strong>/);
    if(!nm) continue;
    const after = inner.slice(inner.indexOf(nm[0]) + nm[0].length);
    const parts = after.split(/<br\s*\/?>|<\/p>\s*<p[^>]*>/).map(text).filter(Boolean);
    if(!parts.length) continue;
    rows[m[1]] = {r: m[1], n: text(nm[1]), t: parts[0]};
  }
  return rows;
}

function render(rows){
  const keys = Object.keys(rows).sort((a, b) => {
    const pa = a.split(".").map(Number), pb = b.split(".").map(Number);
    return pa[0] - pb[0] || pa[1] - pb[1] || pa[2] - pb[2];
  });
  const lines = keys.map(k => JSON.stringify(rows[k]));
  return "/* GENERATED by tools/pin-crkw.js from " + SRC + " — never hand-edit. Each row: a keyword's\n" +
    "   Comprehensive Rules number, its name and the first paragraph that defines it, verbatim. */\n" +
    "(function(root){ var rows = [\n" + lines.join(",\n") + "\n];\n" +
    "var src = " + JSON.stringify(SRC) + ";\n" +
    "if(typeof module === \"object\" && module.exports) module.exports = {src: src, rows: rows};\n" +
    "else root.DAWN_CRKW = {src: src, rows: rows};\n" +
    "})(typeof self !== \"undefined\" ? self : this);\n";
}

if(require.main === module){
  (async () => {
    const res = await fetch(SRC);
    if(!res.ok) throw new Error(SRC + " answered " + res.status);
    const rows = parse(await res.text());
    const n = Object.keys(rows).length;
    if(n < 60) throw new Error("only " + n + " keyword rows read — the chapter's markup moved; read it before pinning");
    const out = render(rows);
    if(process.argv.includes("--check")){
      const old = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
      if(old === out){ console.log("data/crkw.js matches the live chapter (" + n + " rows)"); return; }
      console.log("data/crkw.js DIFFERS from the live chapter (" + n + " rows live) — rerun without --check after reading it");
      process.exit(1);
    }
    fs.writeFileSync(OUT, out);
    console.log("wrote data/crkw.js: " + n + " keyword rows from " + SRC);
  })().catch(e => { console.error(e.message); process.exit(1); });
}
module.exports = {parse, render, SRC};
